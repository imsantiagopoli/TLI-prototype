export function getOrdersBySection(section: string, pipeline?: string): Order[] {
  return orders.filter(
    (o) => o.section === section && (!pipeline || o.pipeline === pipeline)
  )
}

export function getDomesticOrders(): Order[] {
  return orders.filter((o) => o.pipeline === "domestic")
}

export function getDirectOrders(): Order[] {
  return orders.filter((o) => o.pipeline === "direct")
}

export function getTotalRevenue(pipeline?: string): number {
  const filtered = pipeline ? orders.filter((o) => o.pipeline === pipeline) : orders
  return filtered.reduce((sum, o) => sum + o.salesValue, 0)
}
