export function getContainersBySection(section: string): Container[] {
  return containers.filter((c) => c.section === section)
}

export function getHotContainers(): Container[] {
  return containers.filter((c) => c.isHot)
}

export function getCriticalContainers(): Container[] {
  return containers.filter((c) => c.urgency === "critical")
}

export function getUniqueContainers(): Container[] {
  const seen = new Set<string>()
  return containers.filter((c) => {
    if (seen.has(c.containerNumber)) return false
    seen.add(c.containerNumber)
    return true
  })
}
